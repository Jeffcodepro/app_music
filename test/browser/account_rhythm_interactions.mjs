export default async function verifyAccountRhythmInteractions(page) {
  const origin='http://127.0.0.1:3001'
  if(new URL(page.url()).origin!==origin)throw Error('Use isolated browser server')
  await page.setViewportSize({width:360,height:844})
  await page.goto(origin+'/app/dashboard')
  await page.getByRole('button',{name:'Abrir ou recolher menu',exact:true}).click()
  await page.locator('.app-shell.is-drawer-open').waitFor()
  await page.locator('.sidebar-account').click()
  await page.getByRole('link',{name:'Configurações',exact:true}).click()
  await page.waitForURL('**/app/perfil')
  const closed=await page.locator('.app-shell').evaluate(n=>!n.classList.contains('is-drawer-open')&&!n.querySelector('.app-workspace').inert)
  if(!closed)throw Error('Account navigation left drawer open')
  await page.getByRole('link',{name:'Dados pessoais',exact:true}).click()
  await page.getByLabel('Nome completo',{exact:true}).fill('Marina de Teste')
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click()
  await page.getByText('Sua conta foi atualizada com sucesso.',{exact:true}).waitFor()
  await page.reload()
  if(await page.getByLabel('Nome completo',{exact:true}).inputValue()!=='Marina de Teste')throw Error('Personal change did not persist')
  await page.getByLabel('Nome completo',{exact:true}).fill('Marina')
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click()
  await page.getByText('Sua conta foi atualizada com sucesso.',{exact:true}).waitFor()
  await page.getByRole('link',{name:'Dados de acesso',exact:true}).click()
  await page.getByLabel('E-mail *',{exact:true}).fill('unaccepted@example.test')
  await page.getByLabel('Senha atual *',{exact:true}).fill('wrong-password')
  const rejection=page.waitForResponse(r=>['POST','PUT'].includes(r.request().method())&&new URL(r.url()).pathname==='/users')
  await page.getByRole('button',{name:'Salvar credenciais',exact:true}).click()
  if((await rejection).status()!==422)throw Error('Credentials were not rejected')
  await page.locator('.account-links').waitFor()
  await page.getByRole('link',{name:'Visão geral',exact:true}).click()
  await page.getByText('compact@example.test',{exact:true}).waitFor()
  await page.goto(origin+'/app/playground?activity=ritmica&level=2&meter_id=mixed&activity_mode=precision')
  const state=()=>page.locator('[data-rhythm-player-exercise-signature-value]').evaluate(n=>({id:n.dataset.rhythmPlayerExerciseSignatureValue,meter:JSON.parse(n.dataset.rhythmPlayerMeterValue)}))
  const first=await state()
  await page.reload()
  if((await state()).id!==first.id)throw Error('Reload rerolled mixed meter')
  const rounds=[first]
  for(let i=0;i<4;i++){
    const previous=rounds.at(-1).id
    await page.getByRole('link',{name:'Próximo exercício',exact:true}).click()
    await page.waitForFunction(old=>document.querySelector('[data-rhythm-player-exercise-signature-value]')?.dataset.rhythmPlayerExerciseSignatureValue!==old,previous)
    rounds.push(await state())
    if(await page.locator('select[name=meter_id]').inputValue()!=='mixed')throw Error('Lost mixed preference')
  }
  if(new Set(rounds.map(r=>`${r.meter.numerator}/${r.meter.denominator}`)).size<2)throw Error('Mixed did not vary formulas')
  await page.locator('.theme-picker > summary').click()
  await page.getByRole('button',{name:'Sistema',exact:true}).click()
  await page.emulateMedia({colorScheme:'light'})
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light')
  await page.emulateMedia({colorScheme:'dark'})
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark')
  await page.reload()
  const theme=await page.evaluate(()=>({preference:document.documentElement.dataset.themePreference,resolved:document.documentElement.dataset.theme}))
  if(theme.preference!=='system'||theme.resolved!=='dark')throw Error('System preference did not persist')
  await page.getByRole('button',{name:'Abrir ou recolher menu',exact:true}).click()
  await page.locator('.app-shell.is-drawer-open').waitFor()
  await page.keyboard.press('Escape')
  const focus=await page.getByRole('button',{name:'Abrir ou recolher menu',exact:true}).evaluate(n=>n===document.activeElement)
  if(!focus)throw Error('Drawer did not restore focus')
  return {drawerClosedOnAccountNavigation:closed,personalDataPersisted:true,credentialsRejected:422,emailUnchanged:true,rounds,theme,escapeRestoresFocus:focus}
}
